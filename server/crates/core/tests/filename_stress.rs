/// A small deterministic PRNG (SplitMix64). It exists only to vary the
/// generated population from the seed; it is not a security primitive.
struct Rng(u64);

impl Rng {
    fn new(seed: u64) -> Self {
        Self(seed)
    }

    fn next_u64(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    fn below(&mut self, n: usize) -> usize {
        (self.next_u64() % n as u64) as usize
    }

    fn pick<'a, T>(&mut self, items: &'a [T]) -> &'a T {
        &items[self.below(items.len())]
    }

    fn range(&mut self, lo: i64, hi: i64) -> i64 {
        lo + (self.next_u64() % ((hi - lo + 1) as u64)) as i64
    }
}

/// A field assertion. Positive families list the fields their convention
/// defines; adverse families list only the absences their safety contract
/// guarantees.
#[derive(Clone, Debug)]
enum Check {
    Title(String),
    Kind(MediaKind),
    Year(i32),
    YearNone,
    Season(i32),
    SeasonNone,
    Episode(i32),
    EpisodeNone,
    EpisodeEnd(i32),
    EpisodeEndNone,
    Absolute(bool),
}

/// How to feed the name to the parser. Folder context is part of the
/// season-folder family; everything else is a bare basename.
#[derive(Clone, Debug)]
enum Mode {
    Plain,
    Folder {
        folder_title: Option<String>,
        season: Option<i32>,
    },
    Parent(String),
}

#[derive(Clone, Debug)]
struct Case {
    family: &'static str,
    input: String,
    mode: Mode,
    checks: Vec<Check>,
}

#[derive(Clone, Debug)]
struct Manifest {
    schema_version: i64,
    generator_version: i64,
    seed: u64,
    total_cases: usize,
    families: BTreeMap<String, usize>,
    max_input_bytes: usize,
    local_case_budget: usize,
    local_byte_budget: u64,
    fingerprint: u64,
}

fn dotted(title: &str) -> String {
    title.replace(' ', ".")
}

fn plain(family: &'static str, input: String, checks: Vec<Check>) -> Case {
    Case {
        family,
        input,
        mode: Mode::Plain,
        checks,
    }
}

fn folder(
    family: &'static str,
    input: String,
    folder_title: Option<&str>,
    season: Option<i32>,
    checks: Vec<Check>,
) -> Case {
    Case {
        family,
        input,
        mode: Mode::Folder {
            folder_title: folder_title.map(str::to_string),
            season,
        },
        checks,
    }
}

fn parent(family: &'static str, input: String, parent_name: &str, checks: Vec<Check>) -> Case {
    Case {
        family,
        input,
        mode: Mode::Parent(parent_name.to_string()),
        checks,
    }
}

fn build_numeric_title_year(count: usize, rng: &mut Rng, _max: usize) -> Vec<Case> {
    let mut out = Vec::with_capacity(count);
    for i in 0..count {
        let title = *rng.pick(NUMERIC_TITLES);
        let year = rng.range(1912, 2017) as i32;
        let input = if i % 2 == 0 {
            format!("{title} ({year}).mkv")
        } else {
            format!("{title} ({year}).1080p.BluRay.mkv")
        };
        out.push(plain(
            "numeric_title_year",
            input,
            vec![
                Check::Title(title.to_string()),
                Check::Year(year),
                Check::Kind(MediaKind::Movie),
                Check::SeasonNone,
                Check::EpisodeNone,
            ],
        ));
    }
    out
}

