//! Deterministic generated-stress harness for the filename parser.
//!
//! This is a bounded robustness and convention check, not an accuracy
//! benchmark. It generates fictional names in memory from explicit template
//! families, parses them with the shipped `nightjar-core` API, and asserts the
//! stable fields each convention defines. Ambiguous and adverse families assert
//! only safety invariants: no panic, a bounded input, and no invented episode or
//! year where the template supplies none.
//!
//! The generator is deterministic. The seed, version, per-family counts, input
//! bound and resource budget are recorded in `stress/manifest.json` and
//! cross-checked here. The generated bulk output is **not** committed: the run
//! rebuilds it from the seed, and a fingerprint over the generated inputs is
//! compared with the manifest so a changed seed or family accounting fails.
//!
//! Nothing here reads the network, the sealed held-out set, or any private
//! path. The names are invented; none is a real title.

