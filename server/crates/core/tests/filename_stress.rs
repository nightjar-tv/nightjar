#[test]
fn seed_mutation_is_caught() {
    let mut manifest = load_manifest().unwrap();
    manifest.seed ^= 1;
    let err = validate_manifest(&manifest).unwrap_err();
    assert!(err.contains("seed"), "{err}");

    let base = fingerprint(&generate_all(SEED, MAX_INPUT_BYTES));
    let altered = fingerprint(&generate_all(SEED ^ 1, MAX_INPUT_BYTES));
    assert_ne!(
        base, altered,
        "changing the seed did not change the generated cases"
    );
}

